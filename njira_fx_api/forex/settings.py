def _drf_yasg_templates_dir() -> str:
    """Return the drf-yasg templates directory from the installed package."""
    spec = importlib.util.find_spec('drf_yasg')
    if spec is None or not spec.origin:
        return ''
    return os.path.join(os.path.dirname(spec.origin), 'templates')


